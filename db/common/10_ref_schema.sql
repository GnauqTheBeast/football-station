-- Reference / lookup tables owned by the master and replicated
-- master -> station. The station NEVER publishes these (only demo.message
-- is published station -> master), so there is no replication loop.
--
-- These tables exist on every node so logical replication (which copies
-- rows, not schema) has somewhere to write. They are published only on the
-- master; see db/master/10_publication.sql.
CREATE SCHEMA IF NOT EXISTS ref;

CREATE TABLE IF NOT EXISTS ref.team (
  id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name      text NOT NULL,
  code      text NOT NULL,
  city      text,
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS ref.match (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  home_team  text NOT NULL,
  away_team  text NOT NULL,
  kickoff_at timestamptz NOT NULL,
  venue      text,
  updated_at timestamptz NOT NULL DEFAULT now()
);
